def get_subject_image(subject_name):
    """Returns image path for a subject"""
    subject_lower = subject_name.lower().strip()

    if any(word in subject_lower for word in ['операционные', 'осиc', 'системы']):
        return 'os.png'
    elif any(word in subject_lower for word in ['графический', 'дизайн', 'мультимедиа']):
        return 'graf.png'
    elif any(word in subject_lower for word in ['алгоритмизации', 'программирования', 'программирование']):
        return 'po.png'
    elif any(word in subject_lower for word in ['физическая','культура']):
        return 'fizra.png'
    elif any(word in subject_lower for word in ['информационные','технологии']):
        return 'texno.png'
    elif any(word in subject_lower for word in ['дискретная','математика','математическая логика']):
        return 'dismat.png'
    elif any(word in subject_lower for word in ['инструментальные','средства','программного']):
        return 'instrym.png'
    elif any(word in subject_lower for word in ['высшей','высшая']):
        return 'vimat.png'
    elif any(word in subject_lower for word in ['веб','приложения']):
        return 'veb.png'
    else:
        return 'project.png'

def format_excel_width(writer):
    """Auto-adjust Excel column widths based on content and apply polished worksheet styles."""
    from openpyxl.utils import get_column_letter
    from openpyxl.styles import Font, Alignment, PatternFill, Border, Side

    header_fill = PatternFill(start_color='FFD6E4FF', end_color='FFD6E4FF', fill_type='solid')
    odd_row_fill = PatternFill(start_color='FFF8FAFC', end_color='FFF8FAFC', fill_type='solid')
    border_side = Side(border_style='thin', color='FFCBD5E1')
    border = Border(left=border_side, right=border_side, top=border_side, bottom=border_side)
    header_font = Font(bold=True, color='FF1F2937')
    header_align = Alignment(horizontal='center', vertical='center', wrap_text=True)
    body_align = Alignment(vertical='center', wrap_text=True)

    for sheet_name in writer.sheets:
        worksheet = writer.sheets[sheet_name]
        worksheet.sheet_view.showGridLines = False

        # Style header row
        for cell in worksheet[1]:
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = header_align
            cell.border = border

        # Style data rows
        for row_idx, row in enumerate(worksheet.iter_rows(min_row=2, max_row=worksheet.max_row, max_col=worksheet.max_column), start=2):
            row_fill = odd_row_fill if row_idx % 2 == 0 else None
            for cell in row:
                if row_fill:
                    cell.fill = row_fill
                cell.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
                cell.border = border
                if cell.col_idx == 1:
                    cell.alignment = Alignment(horizontal='left', vertical='center', wrap_text=True)

        # Freeze the header row and first column for better navigation
        if worksheet.max_row > 1 and worksheet.max_column > 1:
            worksheet.freeze_panes = 'B2'

        # Adjust column widths
        for column in worksheet.columns:
            max_length = 0
            column_letter = get_column_letter(column[0].column)
            for cell in column:
                try:
                    if cell.value is not None:
                        cell_len = len(str(cell.value))
                        if cell_len > max_length:
                            max_length = cell_len
                except Exception:
                    pass

            adjusted_width = min((max_length + 4) * 1.15, 40)
            worksheet.column_dimensions[column_letter].width = adjusted_width

def get_passing_grade(grading_system):
    """Get passing grade for grading system"""
    if not grading_system:
        return 60

    if grading_system.system_type == 'letter':
        letter = grading_system.passing_grade.upper()
        if letter == 'A': return 90
        elif letter == 'B': return 80
        elif letter == 'C': return 70
        elif letter == 'D': return 60
        else: return 50
    else:
        return grading_system.passing_grade
