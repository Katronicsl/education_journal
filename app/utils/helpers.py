def get_universities_data():
    """Get all universities with courses and groups"""
    univs = University.query.all()
    univs_data = {}
    for u in univs:
        courses = {}
        for c in u.courses:
            groups = [g.name for g in c.groups]
            courses[c.name] = groups
        univs_data[u.name] = courses
    return univs_data

